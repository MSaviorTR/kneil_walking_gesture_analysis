"""Write tests/kneil_test_vectors.h from tools/test_vectors.npz (raw windows, expected features and classes)."""
import numpy as np, os
H = os.path.dirname(os.path.abspath(__file__)); T = np.load(os.path.join(H, 'test_vectors.npz'))
raw, feat = T['raw'].astype(np.float32), T['feat'].astype(np.float32)
f = lambda v: f'{float(v):.9e}f'
lines = ['/* Generated by tools/gen_test_vectors.py: windows from the synthetic dataset (50 Hz, g, device frame) */',
         '#ifndef KNEIL_TEST_VECTORS_H', '#define KNEIL_TEST_VECTORS_H', '#include <stdint.h>', '#include "kneil_tinyml.h"',
         f'#define KNEIL_TV_N {len(raw)}', f'#if KNEIL_WIN_N != {raw.shape[1]}', '#error "test vectors were made for a different KNEIL_FS_HZ"', '#endif',
         'static const float kneil_tv_raw[KNEIL_TV_N][KNEIL_WIN_N][3] = {']
for w in raw:
    lines.append('  {' + ','.join('{' + ','.join(f(v) for v in s) + '}' for s in w) + '},')
lines += ['};', 'static const float kneil_tv_feat[KNEIL_TV_N][KNEIL_N_FEATURES] = {']
lines += ['  {' + ','.join(f(v) for v in r) + '},' for r in feat]
lines += ['};', 'static const int8_t kneil_tv_class_forest[KNEIL_TV_N] = {' + ','.join(str(int(v)) for v in T['pred_forest']) + '};',
          'static const int8_t kneil_tv_class_tree[KNEIL_TV_N] = {' + ','.join(str(int(v)) for v in T['pred_tree']) + '};', '#endif']
open(os.path.join(os.path.dirname(H), 'tests', 'kneil_test_vectors.h'), 'w').write('\n'.join(lines) + '\n'); print('vectors:', len(raw))

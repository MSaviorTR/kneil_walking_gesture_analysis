"""
KNEIL motion simulation, v1 (walking).

Synthetic 3-axis acceleration at the tibial insert (device frame) for virtual subjects and
patient-like gait conditions, generated by kinematic replay in MuJoCo.

Chain:  virtual subject -> gait parameters -> one-stride pattern (published template, warped and
        modified) -> pelvis motion from stance-foot constraints -> trial with stride-to-stride
        variability -> MuJoCo replay at 1 kHz (specific force at the implant) -> heel-strike
        impact transient -> sensor model -> 100 Hz / +-8 g output with labels and ground truth.

Device frame (from the insert drawings): x anterior, z superior (normal to the insert),
y = z cross x = subject's left (medial in a right knee, lateral in a left knee).

Sources (details in SOURCES below and in the parameter functions):
  template motion   OpenSim example "subject01_walk1" (Gait2354 pipeline, opensim-models, GitHub)
  speed by age/sex  Bohannon & Andrews 2011 (Physiotherapy 97:182), comfortable gait speed
  stride vs speed   Alexander 1984 dimensionless relation, stride/leg = 2.3 * Froude^0.3
  post-TKA gait     Debbi et al. ISB 2013 (2 months after TKA: swing peak 41 deg, extension
                    deficit 8 deg, 0.72 m/s); Cushner et al. 2024 J Arthroplasty (implanted
                    tibial IMU, first 6 weeks: cadence +22 %, speed +50 %, stride +17 %)
  locked knee       hip hiking as main compensation, modest abduction (restricted-knee studies),
                    vaulting; amplitudes solved here so that the swing foot clears the floor
  heel strike       Lafortune 1991 J Biomech (bone-mounted tibial accelerometer, walking:
                    resultant 2.7-3.7 g after foot strike; AP peak 1.26 g shod, 2.33 g barefoot)
Approximate rules (marked APPROX in the code) are stated as such and are meant to be replaced by
dataset regressions (e.g. Fukuchi 2018 WBDS) in v2.
"""

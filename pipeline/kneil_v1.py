REF = dict(femur=0.4552, tibia=0.4251, pelvis=1.0)   # template lengths (m) / scale


def site_xyaxes(yaw_deg=0.0, slope_deg=0.0, roll_deg=0.0):
    """Device axes in tibia coordinates (tibia: X anterior, Y superior, Z right).
    Nominal: x_dev = X, y_dev = -Z (left), z_dev = Y. Mounting errors rotate the device about
    its own axes: yaw about z_dev, posterior slope about y_dev, roll about x_dev."""
    R0 = np.array([[1, 0, 0], [0, 0, 1], [0, -1, 0]], float)      # columns = device axes
    def rot(axis, a):
        a = np.radians(a); c, s = np.cos(a), np.sin(a)
        if axis == 'x': return np.array([[1, 0, 0], [0, c, -s], [0, s, c]])
        if axis == 'y': return np.array([[c, 0, s], [0, 1, 0], [-s, 0, c]])
        return np.array([[c, -s, 0], [s, c, 0], [0, 0, 1]])
    # posterior slope: the insert plane dips posteriorly, so z_dev tilts posteriorly -> rotation
    # about +y_dev (left) by -slope tilts z toward -x
    R = R0 @ rot('z', yaw_deg) @ rot('y', -slope_deg) @ rot('x', roll_deg)
    return R, ' '.join(f'{v:.6f}' for v in np.r_[R[:, 0], R[:, 1]])


def build_model(osim, femur=REF['femur'], tibia=REF['tibia'], pelvis=1.0,
                imu_side='r', imu_pos=(0.005, -0.025, 0.0), mount=(0.0, 0.0, 0.0),
                shin_frac=0.47):
    """Return (MjModel, info). Lengths in m; mount = (yaw, slope, roll) in deg."""
    kf = femur / REF['femur']
    _, xy_imu = site_xyaxes(*mount)
    _, xy_nom = site_xyaxes()
    legs = ''
    for s in 'rl':
        h = osim['hip_' + s] * pelvis
        ax = lambda v: ' '.join(f'{c:g}' for c in v)
        a = osim['hip_axes_' + s]
        imu = (f'<site name="imu" pos="{imu_pos[0]} {imu_pos[1]} {imu_pos[2]}" xyaxes="{xy_imu}"/>'
               if s == imu_side else '')
        legs += f"""
      <body name="femur_{s}" pos="{h[0]} {h[1]} {h[2]}">
        <joint name="hip_flexion_{s}" axis="{ax(a[0])}"/>
        <joint name="hip_adduction_{s}" axis="{ax(a[1])}"/>
        <joint name="hip_rotation_{s}" axis="{ax(a[2])}"/>
        <geom type="capsule" fromto="0 0 0 0 {-femur:.4f} 0" size="0.05" mass="9"/>
        <site name="thigh_{s}" pos="0.06 {-(femur - 0.05):.4f} 0" xyaxes="{xy_nom}"/>
        <body name="tibia_{s}">
          <joint name="knee_tx_{s}" type="slide" axis="1 0 0"/>
          <joint name="knee_ty_{s}" type="slide" axis="0 1 0"/>
          <joint name="knee_angle_{s}" axis="0 0 1"/>
          <geom type="capsule" fromto="0 0 0 0 {-tibia:.4f} 0" size="0.04" mass="3.5"/>
          {imu}
          <site name="shin_{s}" pos="0.025 {-shin_frac * tibia:.4f} 0" xyaxes="{xy_nom}"/>
          <site name="ankle_{s}" pos="0 {-tibia:.4f} 0"/>
        </body>
      </body>"""
    xml = f"""<mujoco model="kneil_v1">
  <option gravity="0 {-G} 0" timestep="{1 / FS}"/>
  <worldbody>
    <body name="pelvis">
      <joint name="pelvis_tx" type="slide" axis="1 0 0"/>
      <joint name="pelvis_ty" type="slide" axis="0 1 0"/>
      <joint name="pelvis_tz" type="slide" axis="0 0 1"/>
      <joint name="pelvis_tilt" axis="0 0 1"/>
      <joint name="pelvis_list" axis="1 0 0"/>
      <joint name="pelvis_rotation" axis="0 1 0"/>
      <geom type="sphere" size="0.09" mass="11"/>{legs}
    </body>
  </worldbody>
  <sensor>
    <accelerometer name="acc_imu" site="imu"/>
    <gyro name="gyr_imu" site="imu"/>
    <accelerometer name="acc_shin_r" site="shin_r"/>
    <gyro name="gyr_shin_r" site="shin_r"/>
    <accelerometer name="acc_shin_l" site="shin_l"/>
    <gyro name="gyr_shin_l" site="shin_l"/>
    <accelerometer name="acc_thigh_r" site="thigh_r"/>
    <accelerometer name="acc_thigh_l" site="thigh_l"/>
  </sensor>
</mujoco>"""
    m = mujoco.MjModel.from_xml_string(xml)
    knee = {k: (lambda th, d=0, f=osim[k]: kf * f(th, d)) for k in osim if k.startswith('knee_')}
    return m, dict(knee=knee, femur=femur, tibia=tibia, pelvis=pelvis, kf=kf, imu_side=imu_side)


def qidx(m):
    return {m.joint(i).name: m.jnt_qposadr[i] for i in range(m.njnt)}


def set_knee_translations(Q, idx, info):
    """Fill the coupled knee translation coordinates from the knee angles (rows = samples)."""
    for s in 'rl':
        th = Q[:, idx['knee_angle_' + s]]
        Q[:, idx['knee_tx_' + s]] = info['knee']['knee_1_' + s](th)
        Q[:, idx['knee_ty_' + s]] = info['knee']['knee_2_' + s](th)
    return Q


def ankle_vectors(m, Q):
    """Ankle centre positions (world axes) for each row of Q; pelvis translation as given."""
    d = mujoco.MjData(m)
    ids = [m.site('ankle_r').id, m.site('ankle_l').id]
    out = np.zeros((len(Q), 2, 3))
    for i, q in enumerate(Q):
        d.qpos[:] = q
        mujoco.mj_kinematics(m, d)
        out[i] = d.site_xpos[ids]
    return out



def stance_profiles(psi, heel_rise=1.0):
    """Ankle-centre height and forward roll of the stance foot vs stance progress psi (0..1),
    shaped to the template (heel rocker 2.4 cm / 3.3 cm, heel rise to 12.8 cm at toe-off)."""
    heel = 1 - raised_cos(np.clip(psi, 0, 1) / 0.2)
    h = 0.024 * heel + heel_rise * 0.128 * np.clip((psi - 0.6) / 0.4, 0, 1) ** 2.2
    d = -0.033 * heel + heel_rise * 0.123 * np.clip((psi - 0.8) / 0.2, 0, 1) ** 2
    return h, d


def stance_weight(phi, to, cto, chs):
    """Share of body support on a leg (phase from its own heel strike)."""
    w = np.zeros_like(phi)
    a = phi < cto
    w[a] = raised_cos(phi[a] / cto)
    b = (phi >= cto) & (phi < chs)
    w[b] = 1.0
    c = (phi >= chs) & (phi < to)
    w[c] = 1 - raised_cos((phi[c] - chs) / (to - chs))
    return w


def phase_warp(TP, to, cto, chs):
    """Smooth periodic map from a leg's own phase to template phase (events aligned)."""
    x = np.array([to - 1, 0, cto, chs, to, 1, 1 + cto])
    y = np.array([TP.phi_to - 1, 0, TP.phi_cto, 0.5, TP.phi_to, 1, 1 + TP.phi_cto])
    return PchipInterpolator(x, y)


def knee_features(TP):
    g = TP.grid
    f = -np.degrees(fourier_eval(TP.leg['knee_angle'], g))     # flexion positive
    st_min = f[(g > 0.25) & (g < 0.55)].min()
    lr = f[g < 0.3].max()
    peak = f[g > 0.6].max()
    return f, dict(min=st_min, lr=lr, peak=peak)


def gait_params(subject, cond, rng):
    """Map a virtual subject and a condition to gait parameters (see module docstring)."""
    p = {}
    # comfortable speed: Bohannon & Andrews 2011 decade means (m/s) by sex
    ages = np.array([25, 35, 45, 55, 65, 75, 88])
    vm = np.array([1.358, 1.433, 1.434, 1.433, 1.339, 1.262, 0.968])
    vf = np.array([1.341, 1.337, 1.390, 1.401, 1.300, 1.239, 0.943])
    v_norm = np.interp(subject['age'], ages, vm if subject['sex'] == 'M' else vf)
    v = v_norm * subject.get('speed_factor', 1.0)
    s = cond.get('severity', 0.0)
    v *= (1 - 0.5 * s)                                  # APPROX: s = 1 -> half normal speed
    if cond.get('locked'):
        v *= 0.6                                        # APPROX: braced/locked walking ~0.6x
    if cond.get('aid') in ('crutches', 'walker'):
        v *= 0.8                                        # APPROX
    p['v'] = float(np.clip(v, 0.25, 1.9))
    # stride length from dimensionless speed (Alexander 1984), leg length ~ 0.53 H
    L_leg = 0.53 * subject['height']
    Fr = p['v'] ** 2 / (G * L_leg)
    # APPROX: coefficient 2.55 (Alexander's form) matches the template subject and adult norms
    p['stride'] = float(2.55 * Fr ** 0.3 * L_leg * subject.get('stride_factor', 1.0))
    p['T'] = p['stride'] / p['v']
    # timing: stance fraction rises at slow speed (APPROX slope), antalgic asymmetry with s
    base_to = float(np.clip(0.639 + 0.06 * (1.08 - p['v']), 0.58, 0.72))
    asym = 0.03 * s + (0.02 if cond.get('locked') else 0.0)
    p['to_a'] = base_to - asym                         # affected (device) leg: shorter stance
    p['to_b'] = base_to + asym
    p['hs_b'] = 0.5 - asym                             # shorter affected single support
    # knee targets (flexion, deg): typical adult values at 1.2 m/s (loading response ~17 deg,
    # swing peak ~62 deg) with subject variation; speed slopes APPROX after Lelas 2003 trends.
    # (The template subject's own 20/69 deg are on the high side; HuGaDB gyro data gave ~54 deg
    # knee range of motion.)
    p['lr_target'] = 17.0 + 12.0 * (p['v'] - 1.2) + subject.get('lr_dev', 0.0)
    p['peak_target'] = 62.0 + 8.0 * (p['v'] - 1.2) + subject.get('peak_dev', 0.0)
    p['severity'] = s
    p['locked'] = bool(cond.get('locked', False))
    p['lock_angle'] = cond.get('lock_angle', 5.0)
    p['ext_deficit'] = 8.0 * s                         # Debbi 2013: ~8 deg at 2 months
    p['swing_scale'] = 1 - 0.5 * s                     # s = 1 -> ~41 deg peak (Debbi: 41 deg)
    p['lr_scale'] = 1 - 0.6 * s                        # stiff loading response
    p['heel_rise_a'] = 1 - 0.5 * s - (0.3 if p['locked'] else 0.0)
    p['clear_req'] = 0.85 * 0.018 * subject['height'] / 1.79   # 85 % of template clearance
    return p


def build_stride(TP, m, info, p, side='r', solve=True, ngrid=NGRID, fixed=None):
    """Return dict with one stride (phase grid from the device-leg heel strike)."""
    A, B = side, ('l' if side == 'r' else 'r')
    g = np.linspace(0, 1, ngrid, endpoint=False)
    idx = qidx(m)
    to_a, to_b, hs_b = p['to_a'], p['to_b'], p['hs_b']
    cto_a = (hs_b + to_b) % 1.0                        # B toe-off, in A phase
    events = dict(hs_a=0.0, to_a=to_a, hs_b=hs_b, to_b=cto_a)
    phiA, phiB = g, (g - hs_b) % 1.0
    warpA = phase_warp(TP, to_a, cto_a, hs_b)
    warpB = phase_warp(TP, to_b, (to_a - hs_b) % 1.0, (1 - hs_b) % 1.0)
    fk, kfeat = knee_features(TP)

    def leg_angles(phi_leg, warp, affected, a_hip, comp):
        tp = warp(phi_leg) % 1.0
        out = {c: fourier_eval(TP.leg[c], tp) for c in LEG_COORDS}
        # hip sagittal amplitude (solved for stride length)
        h = out['hip_flexion']; hm = h.mean()
        out['hip_flexion'] = hm + a_hip * (h - hm)
        # knee
        f = -np.degrees(out['knee_angle'])
        sev = p['severity'] if affected else 0.0
        mn = kfeat['min'] + (p['ext_deficit'] if affected else 0.0)
        lr_t = p['lr_target']
        pk_t = p['peak_target']
        if affected:
            lr_t = mn + (lr_t - mn) * p['lr_scale']
            pk_t = mn + (pk_t - kfeat['min']) * p['swing_scale']
        w_st = max((lr_t - mn) / (kfeat['lr'] - kfeat['min']), 0.05)
        w_sw = max((pk_t - mn) / (kfeat['peak'] - kfeat['min']), 0.05)
        S = raised_cos((tp - 0.45) / 0.2) * (1 - raised_cos((tp - 0.9) / 0.1))
        wgt = w_st + (w_sw - w_st) * S
        fn = mn + (f - kfeat['min']) * wgt
        if affected and p['locked']:
            fn = p['lock_angle'] + 0.03 * (f - kfeat['min'])
        out['knee_angle'] = -np.radians(fn)
        # compensations during this leg's swing (hip abduction = negative adduction)
        if comp is not None:
            out['hip_adduction'] = out['hip_adduction'] - np.radians(comp['abd']) * comp['bump']
        return out

    # compensation windows of the device leg: hiking/abduction from pre-swing to late swing
    # (flat top), vaulting of the other leg around mid-swing (its mid-stance)
    u = ((g - (to_a - 0.08)) % 1.0)
    span = (0.98 - (to_a - 0.08))
    bumpA = np.where(u < span, raised_cos(u / 0.10) * (1 - raised_cos((u - (span - 0.10)) / 0.10)), 0.0)
    bumpV = periodic_bump(g, to_a + 0.05, 0.92)

    def assemble(a_hip, k_comp):
        comp = dict(abd=4.0 * k_comp, bump=bumpA) if k_comp > 0 else None
        la = leg_angles(phiA, warpA, True, a_hip, comp)
        lb = leg_angles(phiB, warpB, False, a_hip, None)
        Q = np.zeros((len(g), m.nq))
        for c in LEG_COORDS:
            Q[:, idx[f'{c}_{A}']] = la[c]
            Q[:, idx[f'{c}_{B}']] = lb[c]
        # pelvis rotations follow the device-leg phase (right-leg template phase)
        tpA = warpA(phiA) % 1.0
        sgn = 1.0 if A == 'r' else -1.0                    # list/rotation flip for a left reference
        Q[:, idx['pelvis_tilt']] = fourier_eval(TP.pelvis['pelvis_tilt'], tpA)
        Q[:, idx['pelvis_list']] = sgn * fourier_eval(TP.pelvis['pelvis_list'], tpA)
        Q[:, idx['pelvis_rotation']] = sgn * fourier_eval(TP.pelvis['pelvis_rotation'], tpA)
        if k_comp > 0:                                     # hip hiking on the swing side
            hike = np.radians(3.0 * k_comp) * bumpA
            Q[:, idx['pelvis_list']] += (-hike if A == 'r' else hike)
        Q = set_knee_translations(Q, idx, info)
        Av = ankle_vectors(m, Q)                           # pelvis translation = 0 here
        ia, ib = (0, 1) if A == 'r' else (1, 0)
        wa = stance_weight(phiA, to_a, cto_a, hs_b)
        wb = stance_weight(phiB, to_b, (to_a - hs_b) % 1.0, (1 - hs_b) % 1.0)
        ha, da = stance_profiles(phiA / to_a, p['heel_rise_a'])
        hb, db = stance_profiles(phiB / to_b, 1.0)
        if k_comp > 0:                                     # vaulting: contralateral heel rise
            hb = hb + 0.02 * k_comp * bumpV
        ty = wa * (ha - Av[:, ia, 1]) + wb * (hb - Av[:, ib, 1])
        T = p['T']
        dA = (np.roll(Av, -1, 0) - np.roll(Av, 1, 0)) / (2 / len(g)) / T     # d/dt
        dda = (np.roll(da, -1) - np.roll(da, 1)) / (2 / len(g)) / T
        ddb = (np.roll(db, -1) - np.roll(db, 1)) / (2 / len(g)) / T
        vx = wa * (dda * (phiA < to_a) - dA[:, ia, 0]) + wb * (ddb * (phiB < to_b) - dA[:, ib, 0])
        vz = -(wa * dA[:, ia, 2] + wb * dA[:, ib, 2])
        vz -= vz.mean()
        L = vx.mean() * T                                  # stride length
        x = np.cumsum(vx) * T / len(g); x -= x[0]
        z = np.cumsum(vz) * T / len(g)
        Q[:, idx['pelvis_tx']] = x
        Q[:, idx['pelvis_ty']] = ty
        Q[:, idx['pelvis_tz']] = z - z.mean()
        swing_a = (phiA > to_a + 0.02) & (phiA < 0.92)
        clear = (ty + Av[:, ia, 1])[swing_a].min()          # swing ankle height (stance flat = 0)
        return Q, L, clear, dict(wa=wa, wb=wb, swing_h=(ty + Av[:, ia, 1]), swing_mask=swing_a)

    a_hip, k_comp = (1.0, 0.0) if fixed is None else fixed
    if solve:
        # required swing clearance = healthy template clearance (computed once per call)
        for _ in range(3):
            # stride length: secant on hip amplitude
            a0, a1 = 0.8 * a_hip, 1.2 * a_hip
            L0 = assemble(a0, k_comp)[1]; L1 = assemble(a1, k_comp)[1]
            for _ in range(6):
                if abs(L1 - L0) < 1e-9:
                    break
                a2 = a1 + (p['stride'] - L1) * (a1 - a0) / (L1 - L0)
                a2 = float(np.clip(a2, 0.25, 1.8))
                a0, L0, a1 = a1, L1, a2
                L1 = assemble(a1, k_comp)[1]
                if abs(L1 - p['stride']) < 0.002:
                    break
            a_hip = a1
            # clearance: raise compensation until the swing ankle clears like healthy gait
            c = assemble(a_hip, k_comp)[2]
            if c >= p.get('clear_req', 0.0) - 1e-4:
                break
            lo, hi = k_comp, 6.0
            for _ in range(12):
                mid = 0.5 * (lo + hi)
                if assemble(a_hip, mid)[2] >= p['clear_req']:
                    hi = mid
                else:
                    lo = mid
            k_comp = hi
    Q, L, clear, w = assemble(a_hip, k_comp)
    return dict(Q=Q, grid=g, L=L, clear=clear, a_hip=a_hip, k_comp=k_comp, events=events,
                side=A, T=p['T'], weights=w)



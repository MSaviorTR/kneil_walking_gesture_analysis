def fetch(key, folder='data'):
    os.makedirs(folder, exist_ok=True)
    path = os.path.join(folder, os.path.basename(FILES[key]))
    if not os.path.exists(path):
        urllib.request.urlretrieve(BASE + FILES[key], path)
    return path


def fourier_fit(x, y, n, period=1.0):
    w = 2 * np.pi / period
    A = np.column_stack([np.ones_like(x)] + [f(k * w * x) for k in range(1, n + 1)
                                             for f in (np.cos, np.sin)])
    c, *_ = np.linalg.lstsq(A, y, rcond=None)
    return c


def fourier_eval(c, x, period=1.0, deriv=0):
    w = 2 * np.pi / period
    out = np.full_like(x, c[0] if deriv == 0 else 0.0, dtype=float)
    for k in range(1, (len(c) - 1) // 2 + 1):
        a, b, kw = c[2 * k - 1], c[2 * k], k * w
        cs, sn = np.cos(kw * x), np.sin(kw * x)
        if deriv == 0:
            out += a * cs + b * sn
        elif deriv == 1:
            out += kw * (-a * sn + b * cs)
        else:
            out += -kw ** 2 * (a * cs + b * sn)
    return out


def raised_cos(x):
    """0 -> 1 smooth ramp for x in [0, 1]."""
    x = np.clip(x, 0, 1)
    return 0.5 - 0.5 * np.cos(np.pi * x)


def periodic_bump(phi, start, end):
    """Smooth half-sine bump (0..1..0) on the periodic interval [start, end) of phase."""
    L = (end - start) % 1.0
    u = ((phi - start) % 1.0) / max(L, 1e-9)
    return np.where(u < 1.0, np.sin(np.pi * np.clip(u, 0, 1)) ** 2, 0.0)



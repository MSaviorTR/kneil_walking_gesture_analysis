HUGADB_FS = 56.35         # Hz, mean rate reported by the authors (SD 3.2, no time stamps)


def load_hugadb(path):
    """Shin signals rotated to anatomical axes (x anterior, y left, z superior), in g and deg/s.
    z from standing gravity; y from the main gyroscope axis in walking (unclipped samples);
    y sign from mid-swing (shank angular velocity points to the subject's right)."""
    d = pd.read_csv(path, sep='\t', comment='#')
    act = d['act'].values
    out = {}
    for leg, side in (('rs', 'r'), ('ls', 'l')):
        ra = d[[f'acc_{leg}_{a}' for a in 'xyz']].values
        rg = d[[f'gyro_{leg}_{a}' for a in 'xyz']].values
        acc, gyr = ra / 16384.0, rg * 2000 / 32768
        st, wk = act == 8, act == 1
        if st.sum() < 30 or wk.sum() < 200:
            continue
        z = acc[st].mean(0); z /= np.linalg.norm(z)
        ok = wk & (np.abs(rg) < 32767).all(1)
        Gm = gyr[ok] - gyr[ok].mean(0)
        y = np.linalg.eigh(Gm.T @ Gm)[1][:, -1]
        y -= (y @ z) * z; y /= np.linalg.norm(y)
        om = gyr[wk] @ y
        big = np.abs(om) > np.percentile(np.abs(om), 97)
        if om[big].mean() > 0:
            y = -y
        x = np.cross(y, z)
        Rm = np.vstack([x, y, z])
        out[side] = dict(acc=acc @ Rm.T, gyr=gyr @ Rm.T, act=act,
                         gyro_amplified=bool(np.percentile(np.abs(om), 97) > 1000))
    return out


def strides_midswing(acc, gyr, fs, mask=None, tmin=0.75, tmax=1.7, npts=101):
    """Cut strides between mid-swing peaks of the sagittal shank angular velocity."""
    from scipy.signal import find_peaks
    om = -gyr[:, 1]
    pk, _ = find_peaks(om, height=0.5 * np.percentile(om, 99), distance=int(0.6 * fs))
    S, Ts = [], []
    for a, b in zip(pk[:-1], pk[1:]):
        dur = (b - a) / fs
        if not (tmin <= dur <= tmax):
            continue
        if mask is not None and not mask[a:b + 1].all():
            continue
        u = np.linspace(a, b, npts)
        S.append(np.column_stack([np.interp(u, np.arange(len(acc)), acc[:, k]) for k in range(3)]))
        Ts.append(dur)
    return np.array(S), np.array(Ts)


def skin_hugadb_chain(t, acc, fs_out=HUGADB_FS, f_skin=20.0, z_skin=0.3, rng=None):
    """Mid-shank skin mounting (2nd-order resonance, APPROX) + MPU-type sampling (+-2 g)."""
    from scipy.signal import lti, lsim, cont2discrete, dlsim
    wn = 2 * np.pi * f_skin
    num, den = [wn ** 2], [1, 2 * z_skin * wn, wn ** 2]
    bd, ad, _ = cont2discrete((num, den), 1 / FS, method='bilinear')
    from scipy.signal import lfilter
    a = lfilter(bd.ravel(), ad, acc - acc[0], axis=0) + acc[0]
    sos = butter(4, 25.0, fs=FS, output='sos')
    a = sosfilt(sos, a, axis=0)
    tk = np.arange(t[0], t[-1], 1 / fs_out)
    a = np.column_stack([np.interp(tk, t, a[:, k]) for k in range(3)])
    a = np.round(np.clip(a, -2.0, 2.0 - 1 / 16384) * 16384) / 16384
    return tk, a

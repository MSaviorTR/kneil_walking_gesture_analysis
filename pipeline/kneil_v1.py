H_REF = 1.79      # stature that matches the template segment lengths (Winter ratios)


def smooth_noise(t, step, sd, rng):
    """Smooth random signal: N(0, sd) knots every `step` seconds, cubic interpolation."""
    kn = np.arange(t[0] - step, t[-1] + 2 * step, step)
    return CubicSpline(kn, rng.normal(0, sd, len(kn)))(t)


def impact_kernel(f_n, zeta, fs=FS, dur=0.12):
    tt = np.arange(0, dur, 1 / fs)
    wn = 2 * np.pi * f_n
    wd = wn * np.sqrt(1 - zeta ** 2)
    k = np.exp(-zeta * wn * tt) * np.sin(wd * tt)
    return k / np.abs(k).max()


def sample_subject(rng, kind='patient'):
    """Virtual subject. Patients: typical TKA-revision ages; young: HuGaDB-like adults."""
    if kind == 'young':
        sex = 'M' if rng.random() < 0.78 else 'F'
        age = rng.uniform(19, 30)
    else:
        sex = 'M' if rng.random() < 0.5 else 'F'
        age = float(np.clip(rng.normal(68, 9), 45, 90))
    h_mean, h_sd = (1.76, 0.07) if sex == 'M' else (1.63, 0.065)
    if kind == 'young':
        h_mean += 0.03
    height = float(np.clip(rng.normal(h_mean, h_sd), 1.45, 2.05))
    bmi = float(np.clip(rng.normal(30 if kind == 'patient' else 23, 5 if kind == 'patient' else 3), 18, 48))
    return dict(sex=sex, age=round(age, 1), height=round(height, 3), bmi=round(bmi, 1),
                mass=round(bmi * height ** 2, 1), side=('r' if rng.random() < 0.5 else 'l'),
                speed_factor=float(np.clip(rng.normal(1.0, 0.10), 0.7, 1.3)),
                stride_factor=float(np.clip(rng.normal(1.0, 0.05), 0.85, 1.15)),
                femur_dev=float(rng.normal(0, 0.03)), tibia_dev=float(rng.normal(0, 0.03)),
                lr_dev=float(rng.normal(0, 4.0)), peak_dev=float(rng.normal(0, 4.0)))


def sample_sensor(rng):
    """Implant mounting and accelerometer errors (APPROX generic low-power MEMS values)."""
    return dict(yaw=float(np.clip(rng.normal(0, 4), -10, 10)), slope=float(rng.uniform(0, 7)),
                roll=float(rng.normal(0, 2)),
                pos=(0.005 + rng.normal(0, 0.004), -0.025 + rng.normal(0, 0.005), rng.normal(0, 0.004)),
                bias=rng.normal(0, 0.02, 3).tolist(), scale=rng.normal(0, 0.01, 3).tolist(),
                cross=rng.normal(0, 0.005, 3).tolist(), noise_ug=150.0,
                impact_f=float(rng.uniform(15, 30)), impact_zeta=float(rng.uniform(0.3, 0.5)))


def make_trial(TP, subj, cond, sens, duration, rng, footwear='shoes', shin=False, margin=2.0, f_bw=4.0, jitter_deg=0.0):
    k = subj['height'] / H_REF
    m, info = build_model(TP.osim, femur=REF['femur'] * k * (1 + subj['femur_dev']),
                          tibia=REF['tibia'] * k * (1 + subj['tibia_dev']), pelvis=k,
                          imu_side=subj['side'], imu_pos=sens['pos'],
                          mount=(sens['yaw'], sens['slope'], sens['roll']))
    idx = qidx(m)
    p = gait_params(subj, cond, rng)
    S = build_stride(TP, m, info, p, subj['side'])
    T, g = p['T'], S['grid']
    # kinematic bandwidth: 4 Hz, calibrated on HuGaDB participants 01/03/09/10 (thigh and shin
    # signal ranges), checked on participants 14/15/16/17 (see validate.py)
    nh = int(max(3, np.floor(f_bw * T)))
    coef = {}
    for name, a in idx.items():
        if name.startswith('knee_t'):
            continue
        y = S['Q'][:, a]
        if name == 'pelvis_tx':
            y = y - S['L'] * g
        coef[name] = fourier_fit(g, y, nh)
    # time base and variability
    t = np.arange(-margin, duration + margin, 1 / FS)
    sev = cond.get('severity', 0.0)
    cv_T = 0.02 + 0.02 * sev + (0.01 if cond.get('locked') else 0.0)   # APPROX stride-time CV
    cv_A = 0.03 + 0.02 * sev
    r = smooth_noise(t, T, 1.6 * cv_T, rng)                  # 1.6: smoothing loss, gives cv_T
    phi = np.cumsum(1.0 / (T * (1 + r))) / FS
    phi += rng.uniform(0, 1) - phi[np.argmin(abs(t))]       # random phase at t = 0
    eta = {grp: smooth_noise(t, T, cv_A, rng) for grp in ('hip', 'knee', 'other')}
    Q = np.zeros((len(t), m.nq))
    ph = phi % 1.0
    for name, c in coef.items():
        y = fourier_eval(c, ph)
        grp = 'hip' if name.startswith('hip_flexion') else 'knee' if name.startswith('knee') else 'other'
        y = c[0] + (y - c[0]) * (1 + eta[grp])
        Q[:, idx[name]] = y
    Q[:, idx['pelvis_tx']] += np.cumsum(S['L'] * (1 + eta['hip']) * np.gradient(phi))
    if jitter_deg > 0:   # stride-to-stride irregularity: 3-8 Hz band-limited hip/knee jitter (calibrated, see tstr)
        sos_j = butter(4, [3.0, 8.0], btype='band', fs=FS, output='sos')
        for nm_ in ('hip_flexion_r', 'hip_flexion_l', 'knee_angle_r', 'knee_angle_l'):
            w_ = sosfiltfilt(sos_j, rng.normal(size=len(t))); Q[:, idx[nm_]] += np.radians(jitter_deg) * w_ / (w_.std() + 1e-12)
    Q = set_knee_translations(Q, idx, info)
    QD = np.gradient(Q, 1 / FS, axis=0)
    QDD = np.gradient(QD, 1 / FS, axis=0)
    # replay
    d = mujoco.MjData(m)
    names = ['acc_imu', 'gyr_imu'] + (['acc_shin_r', 'gyr_shin_r', 'acc_shin_l', 'gyr_shin_l',
                                        'acc_thigh_r', 'acc_thigh_l'] if shin else [])
    adr = {n: m.sensor(n).adr[0] for n in names}
    out = {n: np.zeros((len(t), 3)) for n in names}
    tib = m.body('tibia_' + subj['side']).id
    tilt = np.zeros(len(t))
    for i in range(len(t)):
        d.qpos[:], d.qvel[:], d.qacc[:] = Q[i], QD[i], QDD[i]
        mujoco.mj_inverse(m, d)
        for n in names:
            out[n][i] = d.sensordata[adr[n]:adr[n] + 3]
        ax = d.xmat[tib].reshape(3, 3)[:, 1]                    # tibia long axis (superior)
        tilt[i] = np.degrees(np.arctan2(ax[0], ax[1]))          # + = top of tibia forward
    for n in names:
        out[n] = out[n] / (G if n.startswith('acc') else np.pi / 180)   # g and deg/s
    # gait events of the device leg (and the other leg)
    def crossings(x, level):
        return np.flatnonzero((np.floor(x[1:] - level) - np.floor(x[:-1] - level)) > 0) + 1
    ev = dict(hs=crossings(phi, 0.0), to=crossings(phi, S['events']['to_a']),
              hs_other=crossings(phi, S['events']['hs_b']), to_other=crossings(phi, S['events']['to_b']))
    # heel-strike transients (tibia axes: axial +, posterior first, small ML), Lafortune 1991 scale
    v = p['v']
    fw = dict(shoes=1.0, slippers=0.8, barefoot=1.5)[footwear]
    aid = 0.7 if cond.get('aid') in ('crutches', 'walker') else 1.0
    gain = (v / 1.3) ** 1.5 * fw * aid * (1 - 0.4 * sev)
    ker = impact_kernel(sens['impact_f'], sens['impact_zeta'])
    imp = np.zeros((len(t), 3))                                 # in tibia anatomical axes x,y(left),z
    for i0 in ev['hs']:
        a = gain * rng.lognormal(0, 0.15)
        ml = rng.choice([-1, 1]) * 0.3
        seg = slice(i0, min(i0 + len(ker), len(t)))
        n = seg.stop - seg.start
        imp[seg] += np.outer(ker[:n], [-0.8 * a, ml * a, 1.6 * a])
    R, _ = site_xyaxes(sens['yaw'], sens['slope'], sens['roll'])
    Rn, _ = site_xyaxes()
    imp_dev = imp @ (np.linalg.inv(R) @ Rn).T                # nominal device axes -> mounted axes
    acc_true = out['acc_imu'] + imp_dev
    res = dict(t=t, acc_true=acc_true, gyr=out['gyr_imu'], phi=phi, ev=ev, p=p, S=S, Q=Q,
               knee=-np.degrees(Q[:, idx['knee_angle_' + subj['side']]]), tilt=tilt, model=m,
               imp_gain=gain, margin=margin)
    if shin:
        res['shin'] = {s: (out['acc_shin_' + s], out['gyr_shin_' + s]) for s in 'rl'}
        res['thigh'] = {s: out['acc_thigh_' + s] for s in 'rl'}
        res['imp_tibia'] = imp
    return res


def device_output(res, sens, rng, odr=100, range_g=8.0, bits=16):
    """Accelerometer chain: errors, noise, anti-alias filter, decimation, quantization, clipping."""
    a = res['acc_true'].copy()
    C = np.eye(3) + np.diag(sens['scale'])
    c = sens['cross']
    C[0, 1] += c[0]; C[1, 0] += c[0]; C[0, 2] += c[1]; C[2, 0] += c[1]; C[1, 2] += c[2]; C[2, 1] += c[2]
    a = a @ C.T + np.asarray(sens['bias'])
    a += rng.normal(0, sens['noise_ug'] * 1e-6 * np.sqrt(FS / 2), a.shape)
    sos = butter(4, 0.4 * odr, fs=FS, output='sos')
    a = sosfilt(sos, a, axis=0)
    step = FS // odr
    keep = (res['t'] >= 0) & (res['t'] < res['t'][-1] - res['margin'] + 1e-9)
    i = np.flatnonzero(keep)[::step]
    lsb = 2 * range_g / 2 ** bits
    a = np.round(np.clip(a[i], -range_g, range_g - lsb) / lsb) * lsb
    return i, a



def read_osim(path):
    root = ET.parse(path).getroot()
    J = {j.get('name'): j for j in root.iter('CustomJoint')}
    out = {}
    for side in 'rl':
        hip = J['hip_' + side]
        out['hip_' + side] = np.array(hip.find('frames')[0].find('translation').text.split(), float)
        out['hip_axes_' + side] = [np.array(ta.find('axis').text.split(), float)
                                   for ta in hip.iter('TransformAxis')][:3]
        for ta in J['knee_' + side].iter('TransformAxis'):
            if ta.get('name') in ('translation1', 'translation2'):
                mf = ta.find('MultiplierFunction')
                sp = mf.find('function').find('SimmSpline')
                x = np.array(sp.find('x').text.split(), float)
                y = np.array(sp.find('y').text.split(), float) * float(mf.find('scale').text)
                out[f"knee_{ta.get('name')[-1]}_{side}"] = CubicSpline(x, y, bc_type='natural')
        out['ankle_' + side] = np.array(J['ankle_' + side].find('frames')[0]
                                        .find('translation').text.split(), float)
    return out


def gait_events(grf_path):
    g = pd.read_csv(grf_path, sep=r'\s+', skiprows=6)
    ev = {}
    for p in ('', '1_'):
        on = g[p + 'ground_force_vy'].values > 20
        side = 'r' if g[p + 'ground_force_pz'].values[on].mean() > 0 else 'l'
        e = np.flatnonzero(np.diff(on.astype(int))) + 1
        ev['hs_' + side] = g.time.values[e[on[e]]]
        ev['to_' + side] = g.time.values[e[~on[e]]]
    return ev


class Template:
    """One symmetric stride of healthy walking, as functions of gait phase (0 = heel strike)."""

    def __init__(self, n_harm=7, n_leg=10):
        ik = pd.read_csv(fetch('ik'), sep=r'\s+', skiprows=10)
        self.osim = read_osim(fetch('osim'))
        ev = gait_events(fetch('grf'))
        T = float(np.mean([np.diff(ev['hs_r']).mean(), np.diff(ev['hs_l']).mean()]))
        t0 = ik.time.values[0]
        hs_r = ev['hs_r'][ev['hs_r'] > t0][0]
        hs_l = ev['hs_l'][ev['hs_l'] > hs_r][0]
        to_r = ev['to_r'][ev['to_r'] > hs_r][0]
        to_l = ev['to_l'][ev['to_l'] > hs_l][0]
        to_l0 = ev['to_l'][ev['to_l'] > hs_r][0]
        to_r0 = ev['to_r'][ev['to_r'] > hs_l][0]
        self.T, self.v = T, None
        # raw (non-symmetric) fits as functions of phase relative to right heel strike
        x = ((ik.time.values - hs_r) / T)
        self.raw = {}
        for col in ik.columns[1:]:
            is_tr = col in ('pelvis_tx', 'pelvis_ty', 'pelvis_tz')
            y = ik[col].values if is_tr else np.radians(ik[col].values)
            self.raw[col] = fourier_fit(x, y, n_harm)
        self.phi_hs_l = (hs_l - hs_r) / T
        # events of a generic leg, relative to its own heel strike (mean of both legs)
        self.phi_to = 0.5 * ((to_r - hs_r) + (to_l - hs_l)) / T
        self.phi_cto = 0.5 * ((to_l0 - hs_r) + (to_r0 - hs_l)) / T     # contralateral toe-off
        # symmetric leg template on a grid
        g = np.linspace(0, 1, NGRID, endpoint=False)
        self.leg = {}
        for c in LEG_COORDS:
            r = fourier_eval(self.raw[c + '_r'], g)
            l = fourier_eval(self.raw[c + '_l'], g + self.phi_hs_l)
            self.leg[c] = fourier_fit(g, 0.5 * (r + l), n_leg)
        self.pelvis = {}
        for c, sgn in (('pelvis_tilt', 1), ('pelvis_list', -1), ('pelvis_rotation', -1)):
            a = fourier_eval(self.raw[c], g)
            b = fourier_eval(self.raw[c], g + 0.5)
            self.pelvis[c] = fourier_fit(g, 0.5 * (a + sgn * b), 10)
        self.grid = g


